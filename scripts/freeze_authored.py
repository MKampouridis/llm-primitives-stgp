"""Freeze the arm-3 operator library (verbatim copy + lock) and write its catalogue and report.

Usage: uv run python scripts/freeze_authored.py [--allow-partial]

Takes the accepted session of each domain from ``results/wp3/arm3_authoring/`` (protocol_wp3
§3). Refuses to freeze fewer than seven domains unless --allow-partial is given.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from lpstgp.authoring import registry
from lpstgp.authoring.generation import DOMAINS
from lpstgp.config import REPO_ROOT, load_paths
from lpstgp.operators.registry import discover
from lpstgp.strategies.freeze import _usage

ARM = "arm3"


def all_sessions(root: Path) -> list[dict[str, Any]]:
    out = []
    for path in sorted(root.glob("a??_*/summary.json")):
        s = json.loads(path.read_text(encoding="utf-8"))
        log = path.parent / "evaluations.jsonl"
        tools = (
            [json.loads(x)["tool"] for x in log.read_text().splitlines()] if log.exists() else []
        )
        s["checks_used"], s["describes_used"] = tools.count("check"), tools.count("describe")
        out.append(s)
    return out


def catalogue(accepted: Sequence[Mapping[str, Any]], arm6: set[str]) -> str:
    lines = [
        "# Arm 3: the LLM-authored operator library (WP3)",
        "",
        "Generated by `scripts/freeze_authored.py` from the session archives; do not edit. Each",
        "operator was written by `claude-opus-5-5` in an isolated headless Claude Code session",
        "(docs/protocol_wp3.md §3, D-062, D-069), admitted by the gates only, and is frozen",
        "verbatim in `src/lpstgp/authoring/generated/arm3/` with its hash in",
        "`src/lpstgp/authoring/arm3.lock.toml`. The library `arm3` is these 28 operators plus the",
        "WP1 data terminals and core glue. Names marked † coincide with an arm-6 operator name",
        "(independent re-invention: the briefs name no arm-6 operator).",
        "",
        "| domain | signature | lookback | missing | invariances |",
        "|---|---|---:|---|---|",
    ]
    for s in accepted:
        for row in s["operators"]:
            op = row["operator"]
            span = "–".join(str(v) for v in sorted(set(op["lookback_range"])))
            mark = " †" if op["name"] in arm6 else ""
            lines.append(
                f"| {DOMAINS[s['domain']][0]} | `{op['signature']}`{mark} | {span} | "
                f"{op['missing']} | {', '.join(op['invariances']) or '–'} |"
            )
    for s in accepted:
        lines += ["", f"## {DOMAINS[s['domain']][0]} (session {s['slot']})"]
        for row in s["operators"]:
            op = row["operator"]
            lines += [
                "",
                f"### `{op['name']}`",
                "",
                f"`{op['signature']}`",
                "",
                op["summary"],
                "",
                f"**Definition.** {op['definition']}",
                "",
                "**References.**",
                *[f"- {r}" for r in op["references"]],
            ]
    return "\n".join(lines) + "\n"


def report(sessions: Sequence[Mapping[str, Any]], entries: Mapping[str, Any]) -> str:
    models = sorted({m for s in sessions for r in s.get("runs", []) for m in r.get("models", [])})
    lines = [
        "# WP3 arm-3 authoring report",
        "",
        f"Sessions: {len(sessions)}; accepted: {sum(1 for s in sessions if s.get('accepted'))}; "
        f"repair turns: {sum(1 for s in sessions if s.get('repaired'))}; operators frozen: "
        f"{len(entries)}; lock {registry.lock_digest(ARM)[:12]}.",
        f"Model ids seen: {models}; Claude Code: "
        f"{sorted({s.get('claude_version', '') for s in sessions})}; code version "
        f"{sorted({s.get('code_version', '')[:7] for s in sessions})}.",
        "",
        "| session | accepted | problems | checks | describes | turns | minutes | output tokens | est. cost $ |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    totals = {"minutes": 0.0, "output": 0, "cost_usd": 0.0}
    for s in sessions:
        u = _usage(s)
        for k in totals:
            totals[k] += u[k]
        problems = "; ".join(s.get("problems", [])) or "–"
        lines.append(
            f"| {s['slot']} | {'yes' if s.get('accepted') else 'no'} | {problems} | "
            f"{s['checks_used']} | {s['describes_used']} | {u['turns']} | {u['minutes']:.0f} | "
            f"{u['output']:,} | {u['cost_usd']:.2f} |"
        )
    lines += [
        "",
        f"Totals: {totals['minutes']:.0f} minutes of session time, {totals['output']:,} output "
        f"tokens, estimated ${totals['cost_usd']:.2f} at API prices (sessions ran on the PI's "
        "subscription; no API credit was used, D-068).",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--allow-partial", action="store_true")
    args = parser.parse_args()
    paths = load_paths()
    root = paths.results_dir / "wp3" / "arm3_authoring"
    sessions = all_sessions(root)
    accepted = registry.accepted_sessions(root)
    if len({s["domain"] for s in accepted}) != len(accepted):
        raise SystemExit("more than one accepted session for a domain")
    if len(accepted) < len(DOMAINS) and not args.allow_partial:
        raise SystemExit(f"{len(accepted)} of {len(DOMAINS)} domains accepted; use --allow-partial")
    order = list(DOMAINS)
    accepted.sort(key=lambda s: order.index(s["domain"]))
    # The freeze runs once; a re-run (for the documents) only verifies the existing lock.
    entries = registry.read_lock(ARM) or registry.freeze(ARM, accepted)
    specs = registry.load_library(ARM)  # verifies the lock and that every file loads
    assert {s.name for s in specs} == set(entries)
    arm6 = {s.name for s in discover().operators.values()}
    (REPO_ROOT / "docs" / "operators_arm3.md").write_text(
        catalogue(accepted, arm6), encoding="utf-8"
    )
    out = paths.reports_dir / "wp3" / "arm3_authoring.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report(sessions, entries), encoding="utf-8")
    print(f"froze {len(entries)} operators; lock {registry.lock_digest(ARM)[:12]}; report {out}")


if __name__ == "__main__":
    main()
