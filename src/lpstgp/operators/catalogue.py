"""Render the operator catalogue (docs/operators.md) and the arm-6 review checklist from the contracts."""

from __future__ import annotations

from lpstgp.operators.contract import CROSS_DOMAINS, OperatorSpec, TerminalSpec
from lpstgp.operators.registry import Registry

TITLES = {
    "data": "Data terminals",
    "core": "Core: constructors, adaptive thresholds, comparators, logic, regimes",
    "information_theory": "Information theory",
    "information_geometry": "Information geometry",
    "optimal_transport": "Optimal transport",
    "rough_paths": "Rough paths",
    "fractal": "Fractal analysis",
    "statistical_physics": "Statistical physics",
    "spectral": "Spectral methods",
    "technical": "Conventional technical-analysis terminals",
    "directional_change": "Conventional directional-change terminals",
}
ORDER = ("data", "core", *CROSS_DOMAINS, "technical", "directional_change")


def _signature(spec: OperatorSpec) -> str:
    args = [t.__name__ for t in spec.inputs] + [f"{p.name}: {p.kind.__name__}" for p in spec.params]
    return f"`{spec.gp_name}({', '.join(args)}) -> {spec.output.__name__}`"


def _lookback(spec: OperatorSpec) -> str:
    if not spec.params:
        return str(spec.lookback_for({}))
    lows = {p.name: min(p.grid) for p in spec.params}
    highs = {p.name: max(p.grid) for p in spec.params}
    lo, hi = spec.lookback_for(lows), spec.lookback_for(highs)
    return str(lo) if lo == hi else f"{lo}–{hi}"


def _operator_section(spec: OperatorSpec) -> list[str]:
    params = (
        "; ".join(f"{p.name} ∈ {{{', '.join(f'{v:g}' for v in p.grid)}}}" for p in spec.params)
        or "none"
    )
    lines = [
        f"### {spec.key} — {spec.summary}",
        "",
        f"- **Signature:** {_signature(spec)}",
        f"- **Parameters:** {params}",
        f"- **Lookback (bars):** {_lookback(spec)}; earliest output at index lookback − 1",
        f"- **Missing data:** {spec.missing.value}"
        + (f" (min valid share {spec.min_valid:g})" if spec.missing.value == "min_valid" else ""),
        f"- **Invariances:** {', '.join(spec.invariances) or 'none declared'}; size weight {spec.size_weight};"
        f" memory {spec.memory.value}",
        f"- **Definition:** ${spec.definition}$",
        "- **References:** " + "; ".join(spec.references),
        f"- **Reference test:** {spec.reference_test}",
        f"- **Provenance:** {spec.provenance.implemented_by}; specified by {spec.provenance.specified_by};"
        f" {spec.provenance.date}; reviewed by {spec.provenance.reviewed_by or '— (pending)'}",
        "",
    ]
    return lines


def _terminal_table(specs: list[TerminalSpec]) -> list[str]:
    lines = [
        "| Terminal | Type | Lookback | Missing | Definition | Summary |",
        "|---|---|---:|---|---|---|",
    ]
    for s in specs:
        lines.append(
            f"| `{s.key}` | {s.output.__name__} | {s.lookback} | {s.missing.value} | ${s.definition}$ | {s.summary} |"
        )
    refs = sorted({r for s in specs for r in s.references})
    lines += ["", "References: " + "; ".join(refs), ""]
    return lines


def render_catalogue(reg: Registry) -> str:
    lines = [
        "# Operator catalogue (seed library, arm 6)",
        "",
        "Generated from the operator contracts by `scripts/generate_operator_docs.py`; do not edit by hand.",
        "The seed library is expert-specified, AI-assisted and expert-verified (see docs/decisions.md, D-002).",
        "",
        "| Domain | Contracts |",
        "|---|---:|",
    ]
    for domain in ORDER:
        lines.append(f"| {TITLES[domain]} | {len(reg.domain(domain))} |")
    lines.append("")
    for domain in ORDER:
        specs = sorted(reg.domain(domain), key=lambda s: s.key)
        if not specs:
            continue
        lines += [f"## {TITLES[domain]}", ""]
        operators = [s for s in specs if isinstance(s, OperatorSpec)]
        terminals = [s for s in specs if isinstance(s, TerminalSpec)]
        for spec in operators:
            lines += _operator_section(spec)
        if terminals:
            lines += _terminal_table(terminals)
    return "\n".join(lines)


def render_review_checklist(reg: Registry) -> str:
    lines = [
        "# Arm 6 review log",
        "",
        "Arm 6 (the expert-written control) is the WP1 seed library, implemented by Claude Code to the PI's",
        "specification. For each contract, review the definition and reference, the code, and its reference",
        "test, then record the reviewer, date and minutes spent. The total minutes are arm 6's",
        '"human effort" for H2a. Conventional terminals (GP-TA / DC baselines) are listed separately.',
        "",
        "Generated by `scripts/generate_operator_docs.py` only when this file does not exist yet; edit it by hand.",
        "",
        "| Contract | Domain | Definition ✓ | Code ✓ | Reference test ✓ | Reviewer | Date | Minutes | Notes |",
        "|---|---|---|---|---|---|---|---:|---|",
    ]
    for domain in ("core", *CROSS_DOMAINS):
        for spec in sorted(reg.domain(domain), key=lambda s: s.key):
            lines.append(f"| `{spec.key}` | {domain} | | | | | | | |")
    lines += [
        "",
        "## Conventional terminals (baselines)",
        "",
        "| Module | Contracts | Reviewer | Date | Minutes | Notes |",
        "|---|---:|---|---|---:|---|",
    ]
    for domain in ("data", "technical", "directional_change"):
        lines.append(f"| {domain} | {len(reg.domain(domain))} | | | | |")
    lines.append("")
    return "\n".join(lines)
