"""Freeze the generated strategy set: verbatim copies, the lock, the catalogue and the report.

Inputs are the session archives (``results/wp2/strategy_generation/<slot>/summary.json``). Each
accepted file is copied byte for byte to ``generated/<domain>/<sid>__v1.py``, its sha256 checked
against the session's, and locked with its provenance (model, Claude Code version, session id,
brief hash). ``docs/strategies.md`` and the generation report are rendered from the archives.
"""

from __future__ import annotations

import json
import shutil
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from lpstgp.strategies import registry


def summaries(archive_root: Path) -> list[dict[str, Any]]:
    out = []
    for path in sorted(archive_root.glob("s??_*/summary.json")):
        summary = json.loads(path.read_text(encoding="utf-8"))
        log = path.parent / "evaluations.jsonl"
        tools = (
            [json.loads(line)["tool"] for line in log.read_text().splitlines()]
            if log.exists()
            else []
        )
        summary["backtests_used"] = tools.count("backtest")
        summary["checks_used"] = tools.count("check")
        summary["archive"] = str(path.parent)
        out.append(summary)
    return out


def freeze(
    accepted: Sequence[Mapping[str, Any]], generated: Path, lock_path: Path
) -> dict[str, dict]:
    entries = {}
    for s in accepted:
        source = Path(s["archive"]) / "final_strategy.py"
        if registry.file_hash(source) != s["sha256"]:
            raise RuntimeError(f"{s['sid']}: archived file differs from the accepted one")
        target = generated / s["domain"] / f"{s['sid']}__v1.py"
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        entries[s["sid"]] = {
            "sha256": s["sha256"],
            "file": f"{s['domain']}/{target.name}",
            "provenance": {
                "implemented_by": (
                    f"{s['model']} via Claude Code {s['claude_version']} (headless session "
                    f"{s['session_id']}, effort {s['effort']})"
                ),
                "specified_by": f"WP2 generation protocol, brief {s['brief_sha12']}",
                "date": s["finished_utc"][:10],
            },
        }
    registry.write_lock(entries, lock_path)
    return entries


def _usage(s: Mapping[str, Any]) -> dict[str, float]:
    total = {
        "input": 0,
        "cache_read": 0,
        "cache_write": 0,
        "output": 0,
        "cost_usd": 0.0,
        "turns": 0,
        "minutes": 0.0,
    }
    for run in s.get("runs", []):
        u = run.get("usage") or {}
        total["input"] += u.get("input_tokens", 0) or 0
        total["cache_read"] += u.get("cache_read_input_tokens", 0) or 0
        total["cache_write"] += u.get("cache_creation_input_tokens", 0) or 0
        total["output"] += u.get("output_tokens", 0) or 0
        # Claude Code reports the session's cumulative cost in every run of a resumed session.
        total["cost_usd"] = max(total["cost_usd"], run.get("total_cost_usd") or 0.0)
        total["turns"] += run.get("num_turns") or 0
        total["minutes"] += (run.get("duration_ms") or 0) / 60000
    return total


def catalogue(accepted: Sequence[Mapping[str, Any]]) -> str:
    lines = [
        "# Whole LLM strategies (WP2, arms 1, 2a, 2b, 2c)",
        "",
        "Generated by `scripts/strategy_freeze.py` from the session archives; do not edit. Each",
        "strategy was written by `claude-opus-5-5` in an isolated headless Claude Code session",
        "(docs/protocol.md §4) and is frozen verbatim in `src/lpstgp/strategies/generated/`.",
        "Objectives are the median fitness across development instruments (dev-fit: seen by the",
        "agent; dev-holdout: never shown).",
        "",
        "| id | domain | name | signals | lookback | dev-fit | dev-holdout | backtests |",
        "|---|---|---|---|---:|---:|---:|---:|",
    ]
    for s in accepted:
        meta = s["strategy"]
        sig = ", ".join(x["name"] for x in meta["signals"])
        lines.append(
            f"| {s['sid']} | {s['domain']} | {meta['name']} | {sig} | {meta['lookback']} | "
            f"{s['dev_fit']['objective']:.3f} | {s['dev_holdout']['objective']:.3f} | {s['backtests_used']} |"
        )
    for s in accepted:
        meta = s["strategy"]
        lines += [
            "",
            f"## {s['sid']} {meta['name']} ({s['domain']})",
            "",
            f"**Hypothesis.** {meta['hypothesis']}",
            "",
        ]
        lines += [f"**Definition.** {meta['definition']}", "", "**Signals.**", ""]
        for x in meta["signals"]:
            params = (
                ", ".join(f"{k}={v['kind']}({v['default']})" for k, v in x["params"].items())
                or "none"
            )
            lines.append(
                f"- `{x['name']}` on {', '.join(x['inputs'])}; {params}; lookback {x['lookback']}"
            )
        lines += ["", f"Rule lookback {meta['rule_lookback']}; total {meta['lookback']} bars.", ""]
        lines += ["**References.**", ""] + [f"- {r}" for r in meta["references"]]
        lines += [
            "",
            f"**Novelty (agent's claim).** {meta['novelty']}",
            "",
            f"**Limitations.** {meta['limitations']}",
        ]
    return "\n".join(lines) + "\n"


def report(all_sessions: Sequence[Mapping[str, Any]]) -> str:
    accepted = [s for s in all_sessions if s.get("accepted")]
    lines = [
        "# WP2 strategy generation report",
        "",
        f"Sessions: {len(all_sessions)}; accepted: {len(accepted)}; "
        f"repaired: {sum(1 for s in all_sessions if s.get('repaired'))}; "
        f"resumed after interruption: {sum(1 for s in all_sessions if len(s.get('runs', [])) > 1 and not s.get('repaired'))}.",
        f"Model ids seen: {sorted({m for s in all_sessions for r in s.get('runs', []) for m in r.get('models', [])})}; "
        f"Claude Code: {sorted({s.get('claude_version', '') for s in all_sessions})}.",
        "",
        "| slot | accepted | backtests | checks | turns | minutes | output tokens | cache read | est. cost $ | dev-fit | dev-holdout |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    totals = {"minutes": 0.0, "output": 0, "cache_read": 0, "cost_usd": 0.0}
    for s in all_sessions:
        u = _usage(s)
        for k in totals:
            totals[k] += u[k]
        fit = s.get("dev_fit", {}).get("objective")
        hold = s.get("dev_holdout", {}).get("objective")
        lines.append(
            f"| {s['slot']} | {'yes' if s.get('accepted') else 'no: ' + str(s.get('reason', 'gates'))} | "
            f"{s['backtests_used']} | {s['checks_used']} | {u['turns']} | {u['minutes']:.0f} | {u['output']:,} | "
            f"{u['cache_read']:,} | {u['cost_usd']:.2f} | {fit if fit is None else f'{fit:.3f}'} | "
            f"{hold if hold is None else f'{hold:.3f}'} |"
        )
    lines += [
        "",
        f"Totals: {totals['minutes']:.0f} minutes of session time, {totals['output']:,} output tokens, "
        f"{totals['cache_read']:,} cache-read tokens, estimated ${totals['cost_usd']:.2f} at API prices "
        "(sessions ran on the PI's subscription; no API credit was used).",
    ]
    return "\n".join(lines) + "\n"
